const {chromium}=require('playwright');const assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:'chrome',headless:true});
const ctx=await browser.newContext({locale:'ru-RU'});const page=await ctx.newPage();
await page.addInitScript(()=>{try{localStorage.setItem('kzph_user_sizes',JSON.stringify({shoe:'44',clothing:'',uid:''}));}catch(e){}});
const base='http://192.168.28.25:35539';
await page.goto(base+'/search?q='+encodeURIComponent('кеды')+'&attributes='+encodeURIComponent(JSON.stringify({size:'43'})));
await page.locator('.product-card .card-sizes-row').first().waitFor({state:'visible',timeout:30000});
const rows=await page.$$eval('.product-card .card-sizes-row',rs=>rs.map(r=>({chips:[...r.querySelectorAll('button.card-size-btn')].map(b=>({t:b.textContent.trim(),a:b.classList.contains('active'),m:b.classList.contains('is-my-size')})),more:(r.querySelector('.card-size-more')||{}).textContent||''})));
const user=await page.evaluate(()=>getUserSizes());
console.log('user',JSON.stringify(user),'cards',rows.length);
const long=rows.filter(r=>r.chips.some(c=>c.t==='44')&&r.more);
console.log('cards with 44 and +N:',long.length, JSON.stringify(long[0]));
const noActive=rows.filter(r=>!r.chips.some(c=>c.a));
console.log('cards without visible active 43:',noActive.length);
assert.equal(noActive.length,0,'активный 43 виден на всех карточках');
assert.ok(rows.every(r=>r.chips.length<=6));
await page.locator('.product-card').first().screenshot({path:process.argv[2]});
await page.locator('.product-card .card-sizes-row button.card-size-btn.active').first().click();
await page.waitForFunction(()=>!AppState.attributes.size,null,{timeout:20000});
await page.waitForFunction(()=>!document.querySelector('.card-sizes-row button.card-size-btn.active'),null,{timeout:30000});
console.log('after re-click: attributes=',JSON.stringify(await page.evaluate(()=>AppState.attributes)),'url=',new URL(page.url()).search.includes('size')?'has size':'no size');
console.log('PASS stand re-click probe');await browser.close();})().catch(e=>{console.error(e);process.exit(1)});
